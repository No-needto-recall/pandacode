import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const header = '// Generated by scripts/i18n/generate.mjs. Edit shared/i18n instead.\n';
const placeholders = text => [...new Set([...text.matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)].map(match => match[1]))].sort();

export function validateCatalog(catalog, name = 'catalog') {
  for (const [key, entry] of Object.entries(catalog)) {
    if (!/^[a-zA-Z][a-zA-Z0-9_.-]*$/.test(key)) throw new Error(`${name}: invalid message key ${key}`);
    if (!entry || typeof entry.en !== 'string' || typeof entry['zh-CN'] !== 'string' || !entry.en.trim() || !entry['zh-CN'].trim()) {
      throw new Error(`${name}: ${key} needs nonempty en and zh-CN translations`);
    }
    if (Object.keys(entry).some(locale => locale !== 'en' && locale !== 'zh-CN')) throw new Error(`${name}: unsupported locale in ${key}`);
    if (JSON.stringify(placeholders(entry.en)) !== JSON.stringify(placeholders(entry['zh-CN']))) {
      throw new Error(`${name}: placeholder mismatch in ${key}`);
    }
  }
}

export async function generate({ check = false, directory = root } = {}) {
  const source = join(directory, 'shared/i18n');
  const names = (await readdir(join(source, 'catalogs'))).filter(name => name.endsWith('.json')).sort();
  const catalogs = await Promise.all(names.map(async name => {
    const messages = JSON.parse(await readFile(join(source, 'catalogs', name), 'utf8'));
    validateCatalog(messages, name);
    return { name, messages };
  }));
  const keys = new Set();
  for (const { name, messages } of catalogs) {
    for (const key of Object.keys(messages)) {
      if (keys.has(key)) throw new Error(`${name}: duplicate message key ${key}`);
      keys.add(key);
    }
  }
  const core = (await readFile(join(source, 'core.ts'), 'utf8')).replace(/\r\n/g, '\n');
  const changed = [];
  for (const platform of ['desktop', 'mobile']) {
    const messages = Object.fromEntries(catalogs
      .filter(({ name }) => name === 'common.json' || name.startsWith(platform))
      .flatMap(({ messages }) => Object.entries(messages))
      .sort(([a], [b]) => a.localeCompare(b, 'en')));
    const destination = join(directory, platform === 'desktop' ? 'src' : 'mobile/src', 'i18n-generated');
    for (const [name, content] of [
      ['messages.ts', `${header}export const messages = ${JSON.stringify(messages, null, 2)} as const;\n`],
      ['core.ts', header + core],
    ]) {
      const path = join(destination, name);
      const previous = await readFile(path, 'utf8').catch(error => {
        if (error.code === 'ENOENT') return null;
        throw error;
      });
      if (previous?.replace(/\r\n/g, '\n') === content) continue;
      changed.push(path);
      if (!check) {
        await mkdir(destination, { recursive: true });
        await writeFile(path, content, 'utf8');
      }
    }
  }
  if (check && changed.length) throw new Error(`Generated translations are stale; run npm run i18n:generate:\n${changed.join('\n')}`);
  return { keys: keys.size, changed };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const result = await generate({ check: process.argv.includes('--check') });
  console.log(`Validated ${result.keys} translation keys; ${result.changed.length} generated files ${process.argv.includes('--check') ? 'out of date' : 'updated'}.`);
}
